/**
 * Set the current language and update all localized elements in the DOM.
 * @param {string} lang - 'es' or 'en'
 */
function setLanguage(lang) {
    if (!['es', 'en'].includes(lang)) lang = 'es';
    try {
        localStorage.setItem('cofer_lang', lang);
    } catch (e) {
        // Fallback if localStorage is disabled or throws
    }
    document.documentElement.lang = lang;

    const data = i18nData[lang];
    if (!data) return;

    // Update document title
    if (data.page_title) {
        document.title = data.page_title;
    }

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (data[key] !== undefined) {
            el.innerHTML = data[key];
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (data[key] !== undefined) {
            el.setAttribute('placeholder', data[key]);
        }
    });

    // Update aria-labels
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (data[key] !== undefined) {
            el.setAttribute('aria-label', data[key]);
        }
    });

    // Update brochure download buttons href and download attributes
    const brochureFileName = lang === 'en' ? 'COFER - Brochure (EN).pdf' : 'COFER - Brochure (ES).pdf';
    const brochureUri = encodeURI(brochureFileName);
    document.querySelectorAll('.brochure-download-btn').forEach(btn => {
        btn.setAttribute('href', brochureUri);
        btn.setAttribute('download', brochureFileName);
    });

    // Update active styles on language switcher buttons
    document.querySelectorAll('.lang-btn, .lang-btn-mobile').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === lang) {
            btn.classList.add('bg-cofer-orange', 'text-white', 'shadow-sm');
            btn.classList.remove('text-slate-600', 'text-slate-500', 'hover:text-cofer-orange');
        } else {
            btn.classList.remove('bg-cofer-orange', 'text-white', 'shadow-sm');
            btn.classList.add('text-slate-600', 'hover:text-cofer-orange');
        }
    });

    // Update projects toggle button text according to current expansion state
    const proyectosToggle = document.getElementById('proyectos-toggle');
    if (proyectosToggle) {
        const expandido = proyectosToggle.getAttribute('aria-expanded') === 'true';
        const span = proyectosToggle.querySelector('span');
        if (span) {
            span.textContent = expandido ? data.proyectos_btn_less : data.proyectos_btn_more;
        }
    }
}

/**
 * Get current language (stored in localStorage or fallback to Spanish)
 */
function getCurrentLanguage() {
    try {
        const saved = localStorage.getItem('cofer_lang');
        if (saved && ['es', 'en'].includes(saved)) {
            return saved;
        }
    } catch (e) {}
    return 'es';
}

// Bind click events on all language selector buttons
document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('.lang-btn, .lang-btn-mobile').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const lang = btn.getAttribute('data-lang');
            setLanguage(lang);
        });
    });

    // Initialize with stored or default language
    setLanguage(getCurrentLanguage());
});
